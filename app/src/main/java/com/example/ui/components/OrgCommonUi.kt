private val bengaliDigits = charArrayOf('০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯')

fun String.toBengaliDigits(): String = buildString(length) {
    for (ch in this@toBengaliDigits) {
        if (ch in '0'..'9') append(bengaliDigits[ch - '0']) else append(ch)
    }
}

fun formatBdt(amount: Long): String {
    val formatted = NumberFormat.getNumberInstance(Locale.US).format(abs(amount))
    val prefix = if (amount < 0) "-৳" else "৳"
    return "$prefix${formatted.toBengaliDigits()}"
}

fun formatCountBn(count: Int): String = count.toString().toBengaliDigits()

fun shareTextViaSheet(context: Context, subject: String, body: String) {
    val intent = Intent(Intent.ACTION_SEND).apply {
        type = "text/plain"
        putExtra(Intent.EXTRA_SUBJECT, subject)
        putExtra(Intent.EXTRA_TEXT, body)
    }
    context.startActivity(Intent.createChooser(intent, "রিপোর্ট শেয়ার করুন"))
}

